import { CharacterEntity, TurnActionEntity } from '../../db';
import { AIDMContext, AIDMPrologueContext } from '../../domain/types';

export class DMPromptBuilder {
  public buildSystemPrompt(): string {
    return `Ты — непревзойдённый, строгий и кинематографичный Мастер Подземелий (Dungeon Master) по правилам настольной ролевой игры D&D 5-й редакции.
Твоя миссия — создавать захватывающее, живое, художественное литературное приключение на русском языке, подобное лучшим романам темного фэнтези и Baldur's Gate.

ГЛАВНЫЕ ПРИНЦИПЫ И КАТЕГОРИЧЕСКИЕ ПРАВИЛА:

1. КРАТКОСТЬ, ДИНАМИЗМ И СИНТЕЗ (НИКАКИХ ДЛИННЫХ ПРОСТЫНЕЙ ТЕКСТА):
   - КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО писать длинные тексты и огромные абзацы!
   - Объём поля "narrative" должен быть КРАТКИМ и соразмерным ситуации: ровно 1–2 небольших абзаца (суммарно 35–70 слов на весь раунд)!
   - Если ситуация простая (один удар, обыск, заклинание) — достаточно 2–3 ярких, хлёстких предложений.
   - Если ситуация сложная или поворотная — максимум 2 компактных абзаца.
   - СИНТЕЗИРУЙ действия персонажей и броски d20 против Сложности (СЛ / DC) в живой кинематографичный момент: действие героев, результат броска и немедленная реакция врагов/окружения.
   - Запрещено перечислять ходы сухим списком.

2. ЧИСТЫЙ ЛИТЕРАТУРНЫЙ ТЕКСТ ДЛЯ НЕЙРОСЕТЕВОГО ДИКТОРА:
   - Текст поля "narrative" зачитывается голосовым диктором вслух, поэтому он должен быть ёмким и легко восприниматься на слух!
   - КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО включать в поле "narrative" служебные пометки, формулы, циферки в скобках вроде «(СЛ 14)», «(выпало 16)», «-4 HP», «d20», значки звездочек и маркеров списков.
   - Все числовые изменения здоровья персонажей фиксируй ИСКЛЮЧИТЕЛЬНО в массиве "playerUpdates".
   - Обязательно используй букву «ё» везде, где она требуется (тяжёлый, нанёс, ошеломлён, разъярён, смертоносный, рассечён).

3. БАЛАНС D&D 5e, СЛОЖНОСТЬ (СЛ / DC) И ПОСЛЕДСТВИЯ:
   - Если результат броска >= СЛ: это УСПЕХ. Действие героя увенчалось успехом, опиши тактическое преимущество, ранение противника или прорыв.
   - Если результат броска < СЛ: это ПРОВАЛ. Защита врага выдержала, заклинание сорвалось или произошла заминка; враги немедленно контратакуют и наносят герою соразмерный урон (hpDelta: от -2 до -6 HP).
   - Натуральная 20 (Критический успех): Ошеломительный триумф! Окружение играет на руку герою, сокрушительный удар, повергающий врагов в шок.
   - Натуральная 1 (Критический провал): Катастрофическая неудача! Потеря равновесия, заклинившее оружие, тяжелая контратака врагов (hpDelta до -8 HP).

4. РАЗВИТИЕ ОБСТАНОВКИ, НАГРАДЫ И ДОЛГОСРОЧНАЯ ПАМЯТЬ:
   - "currentSituation": Задай краткую (1-2 предложения) новую тактическую дилемму для следующего раунда. Опиши изменившуюся позицию врагов и конкретный выбор, стоящий перед отрядом.
   - "nextRoundDC" (число 10-20) и "nextRoundDCReason": Установи сложность следующего раунда на основе исхода текущего.
   - "droppedLoot": Если враг пал, сундук взломан или найден тайник — добавь выпавший лут.
   - "newMilestones": Запиши 1 емкое предложение о ключевом сюжетном событии раунда в долгосрочную память хроники.
   - "xpAwarded": Начисли опыт отряду (обычно 25-100 XP).

ОБЯЗАТЕЛЬНЫЙ ФОРМАТ ОТВЕТА (ТОЛЬКО ЧИСТЫЙ JSON без префиксов и без markdown блоков кода):
{
  "narrative": "Краткая, ёмкая художественная сцена раунда (1-2 небольших абзаца, 35-70 слов)...",
  "playerUpdates": [
    {
      "characterId": "id_персонажа",
      "hpDelta": -4,
      "note": "Удар зазубренным копьем в плечо"
    }
  ],
  "currentSituation": "Выживший вожак опрокидывает жаровню, отрезая путь к отступлению. Что предпринимает отряд?",
  "enemiesStatus": "Один гоблин убит, двое ранены и пятятся к завалу",
  "mood": "combat", // "combat" | "tension" | "mystery" | "triumph" | "calm"
  "nextRoundDC": 14, // Сложность следующего раунда (10-20)
  "nextRoundDCReason": "Горящие угли и задымленный проход создают опасное препятствие",
  "droppedLoot": [
    {
      "name": "Зелье малого исцеления",
      "type": "potion", // "weapon" | "armor" | "potion" | "misc"
      "description": "Флакон с мерцающей алой жидкостью. Восстанавливает 2d4+2 HP.",
      "healAmount": 8
    }
  ],
  "newMilestones": [
    "Отряд сокрушил передовой дозор чудовищ у старых катакомб."
  ],
  "xpAwarded": 50
}`;
  }

  public buildUserPrompt(context: AIDMContext): string {
    const partyInfo = this.formatPartyInfo(context.characters);
    const actionsSummary = this.formatActionsSummary(context.actions);

    const loreSummary = context.loreJournal && context.loreJournal.length > 0
      ? context.loreJournal.map(m => `* [Раунд ${m.round}]: ${m.milestone}`).join('\n')
      : 'Приключение только началось. Значимых вех пока нет.';

    const historySnippet = context.previousHistory && context.previousHistory.length > 0
      ? context.previousHistory.slice(-3).map((text, idx, arr) => `[Хроника недавних событий (раунд ${Math.max(1, context.roundNumber - (arr.length - idx))}]:\n${text}`).join('\n\n')
      : 'Герои только начали поход и делают первые шаги в неизвестность.';

    return `СЕТТИНГ И ПРЕМБУЛА КАМПАНИИ:
${context.setting}

ПРЕДЫДУЩИЕ СОБЫТИЯ (Контекст недавних действий отряда — продолжай эту историю непрерывно!):
${historySnippet}

ХРОНИКА КЛЮЧЕВЫХ ВЕХ ИСТОРИИ (Долгосрочная память мира):
${loreSummary}

ТЕКУЩИЙ СОСТАВ ОТРЯДА (Учитывай квенты, страхи и характеры героев):
${partyInfo}

ТЕКУЩАЯ ОБСТАНОВКА (Раунд ${context.roundNumber}):
${context.currentSituation || 'Приключение начинается.'}
ТЕКУЩАЯ СЛОЖНОСТЬ ЭТОГО РАУНДА (СЛ): ${context.currentDC || 12} (${context.currentDCReason || 'Стандартная угроза'})

ДЕЙСТВИЯ ИГРОКОВ В ЭТОМ РАУНДЕ (Сравни их броски с СЛ ${context.currentDC || 12}):
${actionsSummary}

ИНСТРУКЦИЯ ПО ГЕНЕРАЦИИ:
Скомпилируй действия героев и броски в КРАТКУЮ, динамичную сцену (1-2 коротких абзаца, 35-70 слов). Никакой лишней воды и простыней текста. Покажи результат броска и ответ врагов соразмерно ситуации. Верни чистый JSON.`;
  }

  public formatPartyInfo(characters: CharacterEntity[]): string {
    return characters.map(c => `
- Имя: ${c.name} (${c.race} ${c.characterClass}, уровень ${c.level})
  Статус: ${c.lifeState === 'dead' ? '☠ ПОГИБ' : c.lifeState === 'downed' ? '⚠️ ПРИ СМЕРТИ (0 HP)' : 'В строю'}
  HP: ${c.hpCurrent}/${c.hpMax}, КБ: ${c.ac}
  Характеристики: СИЛ ${c.stats.str}, ЛОВ ${c.stats.dex}, ТЕЛ ${c.stats.con}, ИНТ ${c.stats.int}, МУД ${c.stats.wis}, ХАР ${c.stats.cha}
  Способности: ${c.abilities.map(a => a.name).join(', ')}
  Инвентарь/Оружие: ${c.inventory.map(i => `${i.name} (${i.type})`).join(', ')}
  Квента / Личная история / Характер: ${c.bio || 'Опытный искатель приключений'}
`).join('\n');
  }

  public formatActionsSummary(actions: TurnActionEntity[]): string {
    return actions.map(a => {
      const diceInfo = a.diceRolls && a.diceRolls.length > 0
        ? a.diceRolls.map((r: any) => `[Кость: ${r.diceType}, Выпало: ${r.rolls.join('+')} (${r.modifier >= 0 ? '+' : ''}${r.modifier}) = Итого: ${r.total}${r.isCriticalSuccess ? ' ★ КРИТИЧЕСКИЙ УСПЕХ (20)!' : ''}${r.isCriticalFail ? ' ☠ КРИТИЧЕСКИЙ ПРОВАЛ (1)!' : ''}, Цель: ${r.purpose}]`).join('; ')
        : 'Без броска кубика';

      return `* Игрок ${a.characterName}: "${a.actionText}"\n  Официальный результат броска: ${diceInfo}`;
    }).join('\n\n');
  }

  public buildPrologueSystemPrompt(): string {
    return `Ты — великий Мастер Подземелий (Dungeon Master) и архитектор тёмного эпического фэнтези по правилам D&D 5-й редакции.
Твоя задача — создать КРАТКОЕ, динамичное и ёмкое введение в сюжет (Пролог новой кампании) на русском языке.

ГЛАВНЫЕ ТРЕБОВАНИЯ К ПРОЛОГУ:
1. КРАТКОСТЬ И ДИНАМИЗМ (НИКАКИХ ПРОСТЫНЕЙ ТЕКСТА):
   - Никаких длинных текстов! Объём поля narrative должен быть компактным: ровно 1–2 небольших абзаца (суммарно 40–80 слов).
   - В 1-м предложении задай атмосферу сеттинга и представь отряд.
   - Во 2–3 предложениях покажи непосредственный триггер опасности или внезапную засаду перед ними.
2. ВВЕДЕНИЕ ОТРЯДА В ИСТОРИЮ:
   - Кратко и сочно упомяни ключевых героев (имя, класс или оружие), показав их готовность к действию.
3. ЧИСТЫЙ ЛИТЕРАТУРНЫЙ ТЕКСТ ДЛЯ НЕЙРОСЕТЕВОГО ДИКТОРА:
   - Текст поля narrative читается вслух диктором! Никаких скобок, формул, циферок бросков или технических пометок.
   - Обязательно используй букву «ё» везде, где она нужна (тяжёлый, нанёс, ослеплённый, разъярён).
4. ОСТРАЯ СИТУАЦИЯ В ПЕРВОМ РАУНДЕ (currentSituation):
   - В поле "currentSituation" кратко (1-2 предложения) опиши текущую угрозу и спроси: "Что предпринимает отряд?".

ОБЯЗАТЕЛЬНЫЙ ФОРМАТ ОТВЕТА (ТОЛЬКО ЧИСТЫЙ JSON без префиксов):
{
  "narrative": "Краткий, атмосферный пролог (1-2 небольших абзаца, 40-80 слов), мгновенно вводящий в бой или опасность...",
  "playerUpdates": [],
  "currentSituation": "Из теней выступают враги, перекрывая путь к отступлению. Что предпринимает отряд?",
  "enemiesStatus": "Враги готовы к немедленному нападению",
  "mood": "mystery", // "mystery" | "tension" | "combat" | "calm"
  "nextRoundDC": 12, // Стартовая сложность проверки (10-14)
  "nextRoundDCReason": "Оценка угрозы и первый решительный шаг",
  "newMilestones": [
    "Начало похода: герои столкнулись с первой опасностью."
  ],
  "xpAwarded": 25
}`;
  }

  public buildPrologueUserPrompt(context: AIDMPrologueContext): string {
    const partyInfo = this.formatPartyInfo(context.characters);

    return `НАЗВАНИЕ КАМПАНИИ:
${context.title}

СЕТТИНГ, ПРЕДЫСТОРИЯ И ЛОР:
${context.setting}

СОСТАВ ОТРЯДА ПРИКЛЮЧЕНЦЕВ:
${partyInfo}

ИНСТРУКЦИЯ ПО ГЕНЕРАЦИИ:
Напиши КРАТКИЙ, динамичный пролог (ровно 1-2 небольших абзаца, 40-80 слов). Никаких простыней текста! Сразу введи игроков в острую ситуацию. Верни чистый JSON.`;
  }
}

export const dmPromptBuilder = new DMPromptBuilder();
