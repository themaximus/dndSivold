export class StoryGeneratorService {
  private aiFactory: AIProviderFactory;

  constructor(aiFactory: AIProviderFactory = aiProviderFactory) {
    this.aiFactory = aiFactory;
  }

  public async generateStory(params?: {
    genre?: string;
    campaignDuration?: 'short' | 'medium' | 'long';
    apiKey?: string;
    model?: string;
  }): Promise<GeneratedStoryResult> {
    const genres = ['fantasy', 'cyberpunk', 'mafia', 'scifi', 'detective', 'horror'];
    const chosenGenre = params?.genre && genres.includes(params.genre.toLowerCase())
      ? params.genre.toLowerCase()
      : genres[Math.floor(Math.random() * genres.length)];

    const durations: Array<'short' | 'medium' | 'long'> = ['short', 'medium', 'long'];
    const chosenDuration = params?.campaignDuration && durations.includes(params.campaignDuration)
      ? params.campaignDuration
      : 'medium';

    const rounds = chosenDuration === 'short' ? 10 : chosenDuration === 'long' ? '20+' : 16;

    // Try AI generation if provider is active
    try {
      const provider = this.aiFactory.getProvider(params?.apiKey, params?.model);
      if (provider.name !== 'Offline Procedural Narrative Engine') {
        const prompt = `Ты — ведущий и сценарист настольных ролевых игр (D&D 5e).
Сгенерируй атмосферную, оригинальную завязку приключения.
Параметры:
- Жанр: ${chosenGenre} (подходит для D&D механик: броски d20, проверки характеристик, раунды)
- Длительность кампании: ${chosenDuration} (${rounds} раундов)

Требования:
- Название кампании (title): звучное, кинематографичное, на русском языке (до 6 слов).
- Преамбула/Сеттинг (setting): 2-4 захватывающих предложения на русском языке. Опиши место действия, атмосферу, завязку тайны или дорожную встречу (с караваном, бродячим торговцем, раненым гонцом или дозорной стражей), и первоначальную цель. ВАЖНО: история НЕ должна начинаться со сплошной драки!

Верни ТОЛЬКО чистый JSON:
{
  "title": "Название кампании",
  "setting": "Описание мира и стартовой завязки сюжета...",
  "genre": "${chosenGenre}",
  "campaignDuration": "${chosenDuration}"
}`;

        const rawResult = await (provider as any).generateRaw?.(prompt);
        if (rawResult) {
          const cleaned = rawResult.trim().replace(/^```json\s*/, '').replace(/\s*```$/, '');
          const parsed = JSON.parse(cleaned);
          if (parsed.title && parsed.setting) {
            return {
              title: parsed.title.trim(),
              setting: parsed.setting.trim(),
              genre: chosenGenre,
              campaignDuration: chosenDuration,
            };
          }
        }
      }
    } catch (e: any) {
      console.warn('AI story generation failed or not configured, using rich procedural story:', e?.message || e);
    }

    // Procedural fallback
    const genrePool = STORY_PRESETS[chosenGenre] || STORY_PRESETS.fantasy;
    const randomItem = genrePool[Math.floor(Math.random() * genrePool.length)];

    return {
      title: randomItem.title,
      setting: randomItem.setting,
      genre: chosenGenre,
      campaignDuration: chosenDuration,
    };
  }
}

export const storyGeneratorService = new StoryGeneratorService();
